    private static final Map<Integer, Integer> S2T = new HashMap<>();
    private static final Map<Integer, Integer> T2S = new HashMap<>();

    static {
        for (String[] pair : PAIRS) {
            int simplified = pair[0].codePointAt(0);
            int traditional = pair[1].codePointAt(0);
            S2T.putIfAbsent(simplified, traditional);
            T2S.putIfAbsent(traditional, simplified);
        }
    }

    static List<String> searchVariants(String query) {
        LinkedHashSet<String> variants = new LinkedHashSet<>();
        variants.add(query);
        String traditional = map(query, S2T);
        String simplified = map(query, T2S);
        if (!traditional.equals(query)) variants.add(traditional);
        if (!simplified.equals(query)) variants.add(simplified);
        return new ArrayList<>(variants);
    }

    private static String map(String source, Map<Integer, Integer> mapping) {
        StringBuilder result = new StringBuilder(source.length());
        for (int offset = 0; offset < source.length();) {
            int cp = source.codePointAt(offset);
            offset += Character.charCount(cp);
            result.appendCodePoint(mapping.getOrDefault(cp, cp));
        }
        return result.toString();
    }
